"""Generate the voice card PCB from voice.py (run with KiCad's bundled Python: pcbnew).

  <KiCad 10>/bin/python.exe gen_pcb.py [--route]     place (and route)
  <KiCad 10>/bin/python.exe gen_pcb.py --finish      one more routing pass on the saved board
  <KiCad 10>/bin/python.exe gen_pcb.py --repair      rip up around open connections and re-route
  <KiCad 10>/bin/python.exe gen_pcb.py --polish      re-route the analog nets listed in pcb_place.POLISH
  <KiCad 10>/bin/python.exe gen_pcb.py --art         redo the front silkscreen texts on the routed board
  <KiCad 10>/bin/python.exe gen_pcb.py --corridor    re-route the nets of pcb_place.CORRIDORS along the edges

Board 50 x 50 mm, 4 layers (docs/spec.md 3.3): F.Cu signals and all parts, In1.Cu solid GND, In2.Cu supply planes
(VA under the analog part, +3V3 under the MCU and the debug edge, +5V in the part-free strip along the right edge),
B.Cu signals only. Placement: pcb_place.py (anchors + blocks, greedy by connectivity). Footprints carry
deterministic schematic paths (gen_sch2's duid), so 'Update PCB from Schematic' keeps working.
With --route, before Freerouting: the locked edge routes (pcb_place.EDGE_ROUTES: SWIO), the AUDIO_GND track, the
corridor nets (CORRIDORS: the loopback) and the short pre-routes (PRE_ROUTE: VCA collectors into the steering pairs);
then every plane-net pad gets its via, the board is exported to Specctra DSN, routed by Freerouting
(FREEROUTING_JAR, default tools/ or archive/tools/freerouting-1.9.0.jar), re-imported, zones filled and stitched.
The rev 0.1 board (design.py, 100 x 100 mm, touch keys) was generated by the version of this script on master.
"""
