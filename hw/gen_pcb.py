PLANE_NETS = ("GND", "VA", "+3V3", "+5V")

# design rules (JLCPCB 4-layer standard, with margin)
TRACK, CLEAR = 0.15, 0.15
POWER_TRACK = 0.3
VIA_D, VIA_DRILL = 0.6, 0.3
EDGE_CLEAR = 0.3
EDGE_BAND = 0.45                                         # outer layers: no tracks / vias this close to the edge


def duid(*parts):
    return str(_uuid.uuid5(NS, "/".join(str(p) for p in parts)))


def in_poly(pts, x, y, margin=0.0):
    """point inside the polygon and at least `margin` away from its edges"""
    inside = False
    for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
        if (y0 > y) != (y1 > y) and x < x0 + (y - y0) * (x1 - x0) / (y1 - y0):
            inside = not inside
        if margin:
            dx, dy = x1 - x0, y1 - y0
            t = max(0.0, min(1.0, ((x - x0) * dx + (y - y0) * dy) / (dx * dx + dy * dy)))
            if math.hypot(x - x0 - t * dx, y - y0 - t * dy) < margin:
                return False
    return inside


# ------------------------------------------------------------------ board helpers
def kicad_net_names():
    """design net -> net name as KiCad's schematic netlist calls it (e.g. '/vcf/N1A' for local nets)"""
    path = os.path.join(OUT, f"{B.PROJECT}.net")
    sch = os.path.join(OUT, f"{B.PROJECT}.kicad_sch")
    if not os.path.exists(path) or os.path.getmtime(path) < os.path.getmtime(sch):
        subprocess.run([S.KICAD_CLI, "sch", "export", "netlist", "--format", "kicadsexpr", "-o", path, sch],
                       check=True, capture_output=True)
    doc = S.parse(open(path, encoding="utf-8").read())
    pin_net = {(p.ref, pin): n for p in D.PARTS for pin, n in p.pins.items()}
    out = {}
    for n in S.find(S.find1(doc, "nets"), "net"):
        name = str(S.find1(n, "name")[1])
        for node in S.find(n, "node"):
            key = (str(S.find1(node, "ref")[1]), str(S.find1(node, "pin")[1]))
            if key in pin_net:
                out[pin_net[key]] = name
                break
    return out


def load_fp(fpid):
    lib, name = fpid.split(":")
    fp = pcbnew.FootprintLoad(os.path.join(FPDIR, lib + ".pretty"), name)
    if fp is None:
        raise RuntimeError(f"footprint {fpid} not found")
    return fp


def set_field(fp, name, value):
    try:
        fp.SetField(name, value)
    except Exception:
        f = pcbnew.PCB_FIELD(fp, fp.GetFieldCount(), name)
        f.SetText(value); f.SetVisible(False)
        fp.AddField(f)
    f = fp.GetField(name)
    if f is not None:
        f.SetVisible(False)
        f.SetLayer(pcbnew.F_Fab)


def units_and_sheets():
    """ref -> (sheet, lowest unit) for footprint paths"""
    res = {}
    for p in D.PARTS:
        sym = S.get_symbol(p.lib_id)
        pinmap = {num: u for u, num, *_ in S.pins(sym)}
        us = sorted({max(pinmap[k], 1) for k in p.pins if k in pinmap} | ({1} if S.units(sym) == 1 else set()))
        u = us[0]
        res[p.ref] = (p.unit_sheets.get(u, p.sheet), u)
    return res


def add_rect(board, layer, x0, y0, x1, y1, width=0.1):
    for a, b in (((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))):
        s = pcbnew.PCB_SHAPE(board)
        s.SetShape(pcbnew.SHAPE_T_SEGMENT)
        s.SetStart(pcbnew.VECTOR2I_MM(*a)); s.SetEnd(pcbnew.VECTOR2I_MM(*b))
        s.SetLayer(layer); s.SetWidth(MM(width))
        board.Add(s)


def zone(board, layer, pts, net=None, rule_area=False, name="", priority=0):
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    ol = z.Outline()
    ol.NewOutline()
    for x, y in pts:
        ol.Append(MM(x), MM(y))
    if rule_area:
        z.SetIsRuleArea(True)
        for m in ("SetDoNotAllowZoneFills", "SetDoNotAllowCopperPour"):
            if hasattr(z, m):
                getattr(z, m)(True)
        z.SetDoNotAllowTracks(False); z.SetDoNotAllowVias(False); z.SetDoNotAllowPads(False)
        z.SetDoNotAllowFootprints(False)
    else:
        z.SetNet(net)
        z.SetLocalClearance(MM(0.2))
        z.SetMinThickness(MM(0.2))
        z.SetThermalReliefGap(MM(0.25))
        z.SetThermalReliefSpokeWidth(MM(0.3))
        z.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
        z.SetAssignedPriority(priority)
    if name:
        z.SetZoneName(name)
    board.Add(z)
    return z


def design_rules(board):
    ds = board.GetDesignSettings()
    ds.SetCopperLayerCount(4)
    ds.SetBoardThickness(MM(1.6))
    board.SetLayerType(pcbnew.In1_Cu, pcbnew.LT_POWER)   # planes: Freerouting keeps signals on F.Cu / B.Cu
    board.SetLayerType(pcbnew.In2_Cu, pcbnew.LT_POWER)
    ds.m_CopperEdgeClearance = MM(EDGE_CLEAR)
    ds.m_TrackMinWidth = MM(TRACK)
    ds.m_MinClearance = MM(CLEAR)
    ds.m_ViasMinSize = MM(0.45)
    ds.m_MinThroughDrill = MM(0.3)
    ds.m_ViasMinAnnularWidth = MM(0.1)
    ds.m_HoleToHoleMin = MM(0.25)
    ds.m_MinSilkTextHeight = MM(0.8)
    ds.m_MinSilkTextThickness = MM(0.15)
    ds.m_TentViasFront = ds.m_TentViasBack = True       # vias under the mask (silkscreen may cross them)
    ds.m_MinResolvedSpokes = 1                           # header pads: one spoke on a crowded outer layer is enough
    ns = ds.m_NetSettings
    nc = ns.GetDefaultNetclass()
    nc.SetTrackWidth(MM(TRACK)); nc.SetClearance(MM(CLEAR))
    nc.SetViaDiameter(MM(VIA_D)); nc.SetViaDrill(MM(VIA_DRILL))
    pw = pcbnew.NETCLASS("Power")
    pw.SetTrackWidth(MM(POWER_TRACK)); pw.SetClearance(MM(CLEAR))
    pw.SetViaDiameter(MM(VIA_D)); pw.SetViaDrill(MM(VIA_DRILL))
    ns.SetNetclass("Power", pw)
    for n in ("GND", "VA", "+3V3", "+5V", "+5V_PRG"):
        ns.SetNetclassPatternAssignment(n, "Power")


# ------------------------------------------------------------------ greedy placement
def tp_label_w(p):
    return 0.3 + len(p.value) * 0.62


def _geom(fp, rot):
    """bbox (relative to position) and pad offsets for a rotation"""
    fp.SetOrientationDegrees(rot)
    fp.SetPosition(pcbnew.VECTOR2I_MM(0, 0))
    bb = fp.GetBoundingBox(False)
    box = (pcbnew.ToMM(bb.GetLeft()), pcbnew.ToMM(bb.GetTop()), pcbnew.ToMM(bb.GetRight()), pcbnew.ToMM(bb.GetBottom()))
    pads = [(pd.GetNumber(), pcbnew.ToMM(pd.GetPosition().x), pcbnew.ToMM(pd.GetPosition().y)) for pd in fp.Pads()]
    return box, pads


def fp_rect(p, fp):
    bb = fp.GetBoundingBox(False)
    r = (pcbnew.ToMM(bb.GetLeft()), pcbnew.ToMM(bb.GetTop()), pcbnew.ToMM(bb.GetRight()), pcbnew.ToMM(bb.GetBottom()))
    if p.lib_id == "Connector:TestPoint":                       # keep the label area free as well
        cy = pcbnew.ToMM(fp.GetPosition().y)
        r = (r[0], min(r[1], cy - 0.5), r[2] + tp_label_w(p), max(r[3], cy + 0.5))
    if p.ref.startswith("J"):                                   # headers: only the part on the board counts
        r = (r[0], max(r[1], 0.0), r[2], min(r[3], H))
        if r[1] < 1.0:                                          # debug edge: pin names below the pads
            r = (r[0], r[1], r[2], r[3] + 2.3)
    return r


def greedy_place(board, fps, placed, step=0.25, clr=0.25):
    rects = []
    padpos = {}                                        # net -> [(x, y)]

    def add_placed(p, fp):
        rects.append(fp_rect(p, fp))
        for pd in fp.Pads():
            n = p.pins.get(pd.GetNumber())
            if n:
                padpos.setdefault(n, []).append((pcbnew.ToMM(pd.GetPosition().x), pcbnew.ToMM(pd.GetPosition().y)))
    for ref in placed:
        add_placed(*fps[ref])
    rects += list(PP.RESERVED.values()) + list(PP.SILK.values())
    todo = [fps[r][0] for r in fps if r not in placed]
    dec_target, dec_block = {}, {}
    for p in todo:
        ic = PP.dec_ic(p)
        if ic:                                          # target: the IC pin on the cap's supply net
            icp, icfp = fps[ic]
            dec_block[p.ref] = PP.block_of(icp)
            supply = [n for n in p.pins.values() if n != "GND"][0]
            pin = PP.dec_pin(p) if hasattr(PP, "dec_pin") else None      # a specific pin of the IC, if given
            for pd in icfp.Pads():
                if (pd.GetNumber() == pin) if pin else icp.pins.get(pd.GetNumber()) == supply:
                    dec_target[p.ref] = (pcbnew.ToMM(pd.GetPosition().x), pcbnew.ToMM(pd.GetPosition().y))
    ux0, uy0, ux1, uy1 = PP.USABLE
    while todo:
        def links(p):
            return sum(1 for n in p.pins.values() if n not in POWER_NETS and n in padpos)
        def rank(q):                                    # test points right after the parts of their net
            n = links(q) + (1.5 if q.lib_id == "Connector:TestPoint" and links(q) else 0)
            return (q.ref in dec_target, n, len(q.pins))
        p = max(todo, key=rank)
        todo.remove(p)
        fp = fps[p.ref][1]
        blk = PP.block_of(p) or dec_block.get(p.ref)
        if p.ref in dec_target:
            tx, ty = dec_target[p.ref]
            region = (max(tx - 5, ux0), max(ty - 5, uy0), min(tx + 5, ux1), min(ty + 5, uy1))
        else:
            region = PP.place_rect(blk)
        rots = (0, 90) if len(p.pins) <= 3 else (0, 90, 180, 270)
        if p.lib_id == "Connector:TestPoint":
            rots = (0,)
        geoms = {r: _geom(fp, r) for r in rots}
        if p.lib_id == "Connector:TestPoint":             # reserve the net-name label right of the pad
            (bx0, by0, bx1, by1), pads = geoms[0]
            geoms[0] = ((bx0, min(by0, -0.5), bx1 + tp_label_w(p), max(by1, 0.5)), pads)
        regions = [region] + [(max(region[0] - g_, ux0), max(region[1] - g_, uy0), min(region[2] + g_, ux1),
                               min(region[3] + g_, uy1)) for g_ in (2.0, 5.0, 10.0, 50.0)]   # fallback: spill over
        c_ = getattr(PP, "BLOCK_CLEARANCE", {}).get(blk, clr)                  # per-block spacing, if any
        for region in regions:
            near = [r for r in rects if r[2] > region[0] - 8 and r[0] < region[2] + 8 and r[3] > region[1] - 8
                    and r[1] < region[3] + 8]
            best = None
            x0, y0, x1, y1 = region
            nx, ny = int((x1 - x0) / step) + 1, int((y1 - y0) / step) + 1
            for rot, (box, pads) in geoms.items():
                for i in range(nx):
                    x = x0 + i * step
                    if x + box[0] < x0 - 0.01 or x + box[2] > x1 + 0.01:
                        continue
                    for j in range(ny):
                        y = y0 + j * step
                        if y + box[1] < y0 - 0.01 or y + box[3] > y1 + 0.01:
                            continue
                        bx0, by0, bx1, by1 = x + box[0] - c_, y + box[1] - c_, x + box[2] + c_, y + box[3] + c_
                        if any(bx0 < r[2] and r[0] < bx1 and by0 < r[3] and r[1] < by1 for r in near):
                            continue
                        cost = 0.0
                        if p.ref in dec_target:
                            tx, ty = dec_target[p.ref]
                            cost = min(math.hypot(x + px - tx, y + py - ty) for num, px, py in pads)
                        else:
                            for num, px, py in pads:
                                n = p.pins.get(num)
                                if n in POWER_NETS or n not in padpos:
                                    continue
                                cost += min(math.hypot(x + px - qx, y + py - qy) for qx, qy in padpos[n])
                        cost += 0.001 * (x + y)                    # tie-break: top-left
                        if best is None or cost < best[0]:
                            best = (cost, x, y, rot)
            if best is not None:
                break
        if best is None:
            print(f"WARNING: no space for {p.ref} ({p.value}) in block {blk}")
            continue
        if region is not regions[0]:
            print(f"placement: {p.ref} ({p.value}) spilled out of block {blk}")
        _, x, y, rot = best
        fp.SetOrientationDegrees(rot)
        fp.SetPosition(pcbnew.VECTOR2I_MM(x, y))
        add_placed(p, fp)


def trim_off_board(fp):
    """drop the silkscreen / fab / courtyard lines of a header that lie outside the board (the protruding pins)"""
    for g in list(fp.GraphicalItems()):
        if g.GetLayer() not in (pcbnew.F_SilkS, pcbnew.F_Fab, pcbnew.F_CrtYd):
            continue
        b = g.GetBoundingBox()
        y0, y1 = pcbnew.ToMM(b.GetTop()), pcbnew.ToMM(b.GetBottom())
        if g.GetLayer() == pcbnew.F_SilkS and (y0 < 0.2 or y1 > H - 0.2):
            fp.Remove(g)


# ------------------------------------------------------------------ build
def build(route=False, passes=30):
    board = pcbnew.NewBoard(PCB)
    design_rules(board)
    add_rect(board, pcbnew.Edge_Cuts, 0, 0, W, H, 0.1)
    nets, fps = make_footprints(board)
    place_and_finish(board, nets, fps, route, passes)


def make_footprints(board, big_libs=("Amplifier_Operational", "MCU_WCH_RiscV", "Regulator_Linear",
                                     "Reference_Voltage", "Connector_Generic", "Transistor_BJT")):
    """nets and footprints of every design part (deterministic schematic paths, LCSC / Sim / Note fields, DNP and
    BOM flags); references on the silkscreen only for the parts of `big_libs`. Returns (net -> NETINFO_ITEM,
    ref -> (part, footprint))."""
    kname = kicad_net_names()
    nets = {}
    for n in sorted({n for p in D.PARTS for n in p.pins.values()}):
        ni = pcbnew.NETINFO_ITEM(board, kname.get(n, n))
        board.Add(ni)
        nets[n] = ni

    paths = units_and_sheets()
    fps = {}
    for p in D.PARTS:
        fp = load_fp(p.fp)
        lib_, name_ = p.fp.split(":")
        fp.SetFPID(pcbnew.LIB_ID(lib_, name_))
        fp.SetReference(p.ref)
        fp.SetValue(p.value)
        sheet, unit = paths[p.ref]
        fp.SetPath(pcbnew.KIID_PATH(f"/{duid('sheet', sheet)}/{duid('sym', p.ref, unit)}"))
        fp.SetSheetname(sheet); fp.SetSheetfile(f"{sheet}.kicad_sch")
        set_field(fp, "LCSC", p.lcsc or "")
        set_field(fp, "Sim", p.sim or "")
        if p.note:
            set_field(fp, "Note", p.note)
        if p.dnp:
            fp.SetDNP(True)
        if not p.bom:
            fp.SetExcludedFromBOM(True); fp.SetExcludedFromPosFiles(True)
        for pad in fp.Pads():
            n = p.pins.get(pad.GetNumber())
            if n in nets:
                pad.SetNet(nets[n])
        ref_ = fp.Reference()
        ref_.SetTextSize(pcbnew.VECTOR2I_MM(0.8, 0.8)); ref_.SetTextThickness(MM(0.15))
        big = p.lib_id.split(":")[0] in big_libs
        if not big:
            ref_.SetLayer(pcbnew.F_Fab)           # passives: references on the fab layer only
        fp.Value().SetLayer(pcbnew.F_Fab); fp.Value().SetVisible(False)
        if p.lib_id == "Connector:TestPoint":
            ref_.SetLayer(pcbnew.F_Fab)
            v = fp.Value(); v.SetLayer(pcbnew.F_SilkS); v.SetVisible(True)
            v.SetTextSize(pcbnew.VECTOR2I_MM(0.8, 0.8)); v.SetTextThickness(MM(0.15))
        board.Add(fp)
        fps[p.ref] = (p, fp)
    return nets, fps


def place_and_finish(board, nets, fps, route, passes):
    def put(ref, x, y, rot=0.0):
        fp = fps[ref][1]
        fp.SetOrientationDegrees(rot)
        fp.SetPosition(pcbnew.VECTOR2I_MM(x, y))

    placed = set()
    for ref, (x, y, rot) in PP.anchors().items():
        put(ref, x, y, rot); placed.add(ref)
        if ref.startswith("J"):
            trim_off_board(fps[ref][1])
            fps[ref][1].SetLocked(True)
    rs = {ref: fp_rect(*fps[ref]) for ref in placed}
    for a in rs:
        for b in rs:
            ra, rb = rs[a], rs[b]
            if a < b and ra[0] < rb[2] and rb[0] < ra[2] and ra[1] < rb[3] and rb[1] < ra[3]:
                print(f"WARNING: anchors {a} and {b} overlap")
    greedy_place(board, fps, placed)
    for p, fp in fps.values():                        # test point labels: right of the pad
        if p.lib_id == "Connector:TestPoint":
            v = fp.Value()
            v.SetKeepUpright(False); v.SetTextAngleDegrees(0)
            v.SetHorizJustify(pcbnew.GR_TEXT_H_ALIGN_LEFT)
            pos = fp.GetPosition()
            v.SetPosition(pcbnew.VECTOR2I(pos.x + MM(0.75), pos.y))

    # card-guide strips: no parts; no copper on the outer layers within 0.8 mm of the side edges
    for x0, x1 in ((0.0, PP.GUIDE), (W - PP.GUIDE, W)):
        kz = zone(board, pcbnew.F_Cu, [(x0, 0), (x1, 0), (x1, H), (x0, H)], rule_area=True, name="CARD_GUIDE")
        kz.SetDoNotAllowFootprints(True)
        if hasattr(kz, "SetDoNotAllowZoneFills"):
            kz.SetDoNotAllowZoneFills(False)

    # edge bands on the outer layers: no tracks or vias within EDGE_BAND of the board edge (keeps the routers off
    # the copper-to-edge clearance; the GND pours still fill them)
    b = EDGE_BAND
    for x0, y0, x1, y1 in ((0, 0, W, b), (0, H - b, W, H), (0, 0, b, H), (W - b, 0, W, H)):
        for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
            ez = zone(board, layer, [(x0, y0), (x1, y0), (x1, y1), (x0, y1)], rule_area=True, name="EDGE_BAND")
            ez.SetDoNotAllowTracks(True); ez.SetDoNotAllowVias(True)
            ez.SetDoNotAllowZoneFills(False)

    # reserved areas (pcb_place.RESERVED, if any): outlined on User.Comments
    import pcb_art as A
    for name, (x0, y0, x1, y1) in PP.RESERVED.items():
        add_rect(board, pcbnew.Cmts_User, x0, y0, x1, y1, 0.1)
        A.text(board, pcbnew.Cmts_User, f"reserved: {name}", (x0 + x1) / 2, (y0 + y1) / 2, 0.8)

    # zones: In1 solid GND, In2 supply planes, GND pour on both outer layers
    e = EDGE_CLEAR
    edge = [(e, e), (W - e, e), (W - e, H - e), (e, H - e)]
    zone(board, pcbnew.In1_Cu, edge, nets["GND"], name="GND_IN1")
    for name, pts in PLANES_IN2.items():
        zone(board, pcbnew.In2_Cu, pts, nets[name.split("@")[0]], name=name.replace("@", "_IN2_"))
    zone(board, pcbnew.F_Cu, edge, nets["GND"], name="GND_F")
    zone(board, pcbnew.B_Cu, edge, nets["GND"], name="GND_B")

    A.labels(board, fps)
    A.place_refs(board)
    A.block_labels(board)
    A.back(board)

    pcbnew.SaveBoard(PCB, board)
    print("saved", PCB)
    if route:
        do_route(board, passes)


# ------------------------------------------------------------------ routing
def freerouting_jar():
    jar = os.environ.get("FREEROUTING_JAR")
    if jar:
        return jar
    root = os.path.dirname(HERE)
    for d in ("tools", os.path.join("archive", "tools")):
        p = os.path.join(root, d, "freerouting-1.9.0.jar")
        if os.path.exists(p):
            return p
    raise SystemExit("Freerouting 1.9.0 not found: set FREEROUTING_JAR")


def freeroute(board, passes):
    """one Freerouting run on the whole board (existing tracks are kept as the starting point)"""
    dsn = os.path.join(OUT, f"{B.PROJECT}.dsn")
    ses = os.path.join(OUT, f"{B.PROJECT}.ses")
    print("DSN export:", pcbnew.ExportSpecctraDSN(board, dsn))
    log = open(os.path.join(OUT, "route.log"), "a")
    subprocess.run(["java", "-jar", freerouting_jar(), "-de", dsn, "-do", ses, "-mp", str(passes), "-mt", "1",
                    "-dct", "0"], check=True, stdout=log, stderr=subprocess.STDOUT)
    print("SES import:", pcbnew.ImportSpecctraSES(board, ses))


def stitch_planes(board):
    for net in PLANE_NETS:
        regions = [pts for name, pts in PLANES_IN2.items() if name.split("@")[0] == net]
        stitch(board, net, regions or None)


def stitch(board, netname, regions=None, clr=0.2, via_d=VIA_D, drill=VIA_DRILL, tw=0.3):
    """give every SMD pad of `netname` (inside one of `regions`, if given) a short track to its own via into the
    plane (skips pads that already have a via of the net within 1.0 mm or where no candidate spot keeps the
    clearance). Runs before routing; the vias and tracks are locked so Freerouting keeps them."""
    net = board.FindNet(netname)
    SC, SS = pcbnew.SHAPE_CIRCLE, pcbnew.SHAPE_SEGMENT
    areas = [z for z in board.Zones() if z.GetIsRuleArea() and z.GetDoNotAllowVias()]
    items = []                                              # (bbox mm, item) of other-net copper

    def bb(it):
        b = it.GetBoundingBox()
        return (pcbnew.ToMM(b.GetLeft()), pcbnew.ToMM(b.GetTop()), pcbnew.ToMM(b.GetRight()),
                pcbnew.ToMM(b.GetBottom()))
    for it in list(board.GetPads()) + list(board.GetTracks()):
        if it.GetNetCode() != net.GetNetCode():
            items.append((bb(it), it))
    vias = [(pcbnew.ToMM(t.GetPosition().x), pcbnew.ToMM(t.GetPosition().y)) for t in board.GetTracks()
            if t.GetClass() == "PCB_VIA" and t.GetNetCode() == net.GetNetCode()]
    allvias = [(pcbnew.ToMM(t.GetPosition().x), pcbnew.ToMM(t.GetPosition().y)) for t in board.GetTracks()
               if t.GetClass() == "PCB_VIA"]
    n0 = len(vias)
    inside = (lambda x, y, m: any(in_poly(r, x, y, m) for r in regions)) if regions else (lambda x, y, m: True)
    for fp in board.GetFootprints():
        for pad in fp.Pads():
            if pad.GetNetCode() != net.GetNetCode() or pad.GetAttribute() != pcbnew.PAD_ATTRIB_SMD:
                continue
            px, py = pcbnew.ToMM(pad.GetPosition().x), pcbnew.ToMM(pad.GetPosition().y)
            if not inside(px, py, 0.6):
                continue
            if any(math.hypot(px - vx, py - vy) < 1.0 for vx, vy in vias):
                continue
            half = max(pcbnew.ToMM(pad.GetSize().x), pcbnew.ToMM(pad.GetSize().y)) / 2
            done = False
            for d in (half + 0.35, half + 0.55, half + 0.8, half + 1.1, half + 1.5, half + 2.0):
                for k in range(16):
                    a = 2 * math.pi * k / 16
                    cx, cy = px + d * math.cos(a), py + d * math.sin(a)
                    if not (PP.GUIDE * 0.5 < cx < W - PP.GUIDE * 0.5 and 0.8 < cy < H - 0.8):
                        continue
                    if not inside(cx, cy, 0.6):
                        continue
                    if any(z.Outline().Collide(pcbnew.VECTOR2I_MM(cx, cy), MM(via_d / 2 + 0.05)) for z in areas):
                        continue
                    if any(math.hypot(cx - vx, cy - vy) < via_d + clr for vx, vy in allvias):
                        continue
                    via_s = SC(pcbnew.VECTOR2I_MM(cx, cy), MM(via_d / 2))
                    trk_s = SS(pcbnew.VECTOR2I_MM(px, py), pcbnew.VECTOR2I_MM(cx, cy), MM(tw))
                    box = (min(px, cx) - 1.5, min(py, cy) - 1.5, max(px, cx) + 1.5, max(py, cy) + 1.5)
                    bad = False
                    for (x0, y0, x1, y1), it in items:
                        if x1 < box[0] or x0 > box[2] or y1 < box[1] or y0 > box[3]:
                            continue
                        for layer in (pcbnew.F_Cu, pcbnew.In1_Cu, pcbnew.In2_Cu, pcbnew.B_Cu):
                            if not it.IsOnLayer(layer):
                                continue
                            sh = it.GetEffectiveShape(layer)
                            if sh.Collide(via_s, MM(clr)) or (layer == pcbnew.F_Cu and sh.Collide(trk_s, MM(clr))):
                                bad = True
                                break
                        if bad:
                            break
                    if bad:
                        continue
                    v = pcbnew.PCB_VIA(board)
                    v.SetPosition(pcbnew.VECTOR2I_MM(cx, cy)); v.SetDrill(MM(drill)); v.SetWidth(MM(via_d))
                    v.SetNet(net); v.SetLocked(True); board.Add(v)
                    t = pcbnew.PCB_TRACK(board)
                    t.SetStart(pcbnew.VECTOR2I_MM(px, py)); t.SetEnd(pcbnew.VECTOR2I_MM(cx, cy))
                    t.SetWidth(MM(tw)); t.SetLayer(pcbnew.F_Cu); t.SetNet(net); t.SetLocked(True); board.Add(t)
                    items.append(((cx - 0.3, cy - 0.3, cx + 0.3, cy + 0.3), t))
                    vias.append((cx, cy)); allvias.append((cx, cy))
                    done = True
                    break
                if done:
                    break
            if not done:
                print(f"stitch: no via spot for {fp.GetReference()} pad {pad.GetNumber()} ({netname})")
    print(f"plane vias {netname}: {len(vias) - n0} new")


def silk_boxes(board):
    """bounding boxes (mm) of the board-level silkscreen art and text on both sides (vias would punch holes)"""
    out = []
    for d in board.GetDrawings():
        if d.GetLayer() in (pcbnew.F_SilkS, pcbnew.B_SilkS):
            b = d.GetBoundingBox()
            out.append((pcbnew.ToMM(b.GetLeft()), pcbnew.ToMM(b.GetTop()), pcbnew.ToMM(b.GetRight()),
                        pcbnew.ToMM(b.GetBottom())))
    return out


def stitch_grid(board, pitch=2.0, via_d=VIA_D, drill=VIA_DRILL):
    """GND vias on a grid wherever both outer pours are filled around the spot: ties the pours to the GND plane
    and fences the analog part (call after a zone fill)."""
    gnd = board.FindNet("GND")
    fills = {}
    for z in board.Zones():
        if not z.GetIsRuleArea() and z.GetNetCode() == gnd.GetNetCode() and z.GetLayer() in (pcbnew.F_Cu, pcbnew.B_Cu):
            fills[z.GetLayer()] = z.GetFilledPolysList(z.GetLayer())
    novia = [z for z in board.Zones() if z.GetIsRuleArea() and z.GetDoNotAllowVias()]
    vias = [(pcbnew.ToMM(t.GetPosition().x), pcbnew.ToMM(t.GetPosition().y)) for t in board.GetTracks()
            if t.GetClass() == "PCB_VIA"]
    holes = [(pcbnew.ToMM(p.GetPosition().x), pcbnew.ToMM(p.GetPosition().y),       # plated and unplated holes,
              max(1.6, pcbnew.ToMM(max(p.GetDrillSize().x, p.GetDrillSize().y)) / 2 + via_d / 2 + 0.35))
             for p in board.GetPads() if p.GetAttribute() in (pcbnew.PAD_ATTRIB_PTH, pcbnew.PAD_ATTRIB_NPTH)]
    silk = silk_boxes(board)
    n = 0
    r = via_d / 2 + 0.15
    ring = [(r * math.cos(k * math.pi / 4), r * math.sin(k * math.pi / 4)) for k in range(8)] + [(0, 0)]
    y = 1.0
    while y < H - 0.9:
        x = 1.0
        while x < W - 0.9:
            ok = all(fills[L].Contains(pcbnew.VECTOR2I_MM(x + dx, y + dy)) for L in (pcbnew.F_Cu, pcbnew.B_Cu)
                     for dx, dy in ring)
            ok = ok and not any(z.Outline().Collide(pcbnew.VECTOR2I_MM(x, y), MM(via_d / 2 + 0.05)) for z in novia)
            ok = ok and all(math.hypot(x - vx, y - vy) > 1.0 for vx, vy in vias)
            ok = ok and all(math.hypot(x - hx, y - hy) > hr for hx, hy, hr in holes)
            ok = ok and not any(b[0] - r < x < b[2] + r and b[1] - r < y < b[3] + r for b in silk)
            if ok:
                v = pcbnew.PCB_VIA(board)
                v.SetPosition(pcbnew.VECTOR2I_MM(x, y)); v.SetDrill(MM(drill)); v.SetWidth(MM(via_d))
                v.SetNet(gnd); board.Add(v)
                vias.append((x, y)); n += 1
            x += pitch / 2
        y += pitch / 2
    print("grid stitch vias:", n)


def remove_dangling(board):
    """delete track pieces with an unconnected end and signal vias used on one layer only (left by the maze
    router or the SES import), repeatedly"""
    n = 0
    while True:
        board.BuildConnectivity()
        c = board.GetConnectivity()
        dead = [t for t in board.GetTracks() if c.TestTrackEndpointDangling(t, False)
                and (t.GetClass() == "PCB_TRACK" or t.GetNetname() not in PLANE_NETS)]
        if not dead:
            break
        for t in dead:
            board.Delete(t)
        n += len(dead)
    if n:
        print(f"removed {n} dangling track pieces")


def fill_and_save(board):
    remove_dangling(board)
    board.BuildConnectivity()
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.BuildConnectivity()
    pcbnew.SaveBoard(PCB, board)


def edge_routes(board):
    """pre-routed, locked tracks of pcb_place.EDGE_ROUTES (long digital lines along the board edges), with a via
    wherever two runs on different layers meet"""
    def pad(value, num):
        fp = board.FindFootprintByReference(PP.by(lambda p: p.value == value))
        return [pd for pd in fp.Pads() if pd.GetNumber() == num][0]
    for name, runs in PP.EDGE_ROUTES.items():
        net = [pad(*p).GetNet() for _, pts in runs for p in pts if isinstance(p[0], str)][0]
        prev = None
        for layer_name, pts in runs:
            layer = board.GetLayerID(layer_name)
            xy = [((lambda q: (pcbnew.ToMM(q.x), pcbnew.ToMM(q.y)))(pad(*p).GetPosition()) if isinstance(p[0], str)
                   else p) for p in pts]
            if prev is not None and prev[0] != layer:
                v = pcbnew.PCB_VIA(board)
                v.SetPosition(pcbnew.VECTOR2I_MM(*xy[0])); v.SetDrill(MM(VIA_DRILL)); v.SetWidth(MM(VIA_D))
                v.SetNet(net); v.SetLocked(True); board.Add(v)
            for a, b in zip(xy, xy[1:]):
                t = pcbnew.PCB_TRACK(board)
                t.SetStart(pcbnew.VECTOR2I_MM(*a)); t.SetEnd(pcbnew.VECTOR2I_MM(*b))
                t.SetWidth(MM(TRACK)); t.SetLayer(layer); t.SetNet(net); t.SetLocked(True); board.Add(t)
            prev = (layer, xy[-1])
        print(f"edge route {name}: {len(runs)} runs")


def audio_ground(board):
    """AUDIO_GND (J1 pin 6, net GND) taken from the output stage (spec 3.3): direct, locked tracks from the ground
    pads of both output bleeders (L, R) to J1 pin 6, routed as a temporary net before anything else (all pads
    also sit on the GND plane)"""
    import pcb_maze
    j1 = board.FindFootprintByReference(PP.by(lambda p: p.value == "BACKPLANE"))
    pads = [pd for pd in j1.Pads() if pd.GetNumber() == "6"]
    for note in ("output bleeder", "output bleeder R"):
        rbl = board.FindFootprintByReference(PP.by(lambda p, n=note: p.note == n))
        pads += [pd for pd in rbl.Pads() if pd.GetNetname() == "GND"]
    gnd = board.FindNet("GND")
    tmp = pcbnew.NETINFO_ITEM(board, "AUDIO_GND")
    board.Add(tmp)
    for pd in pads:
        pd.SetNet(tmp)
    pcb_maze.route_leftovers(board, only=["AUDIO_GND"], lock=True, g=0.1, tw=0.2, clr=CLEAR)
    for it in list(board.GetTracks()) + pads:
        if it.GetNetname() == "AUDIO_GND":
            it.SetNet(gnd)
    board.Remove(tmp)


def pre_route(board):
    """pcb_place.PRE_ROUTE: short analog links routed by the maze router on the empty board, locked"""
    import pcb_maze
    kname = kicad_net_names()
    pcb_maze.route_leftovers(board, only=[kname.get(n, n) for n in PP.PRE_ROUTE], lock=True, g=0.1, tw=TRACK,
                             clr=CLEAR)


def corridor_routes(board, rip=False):
    """pcb_place.CORRIDORS: each net routed by the maze router with a temporary keep-out over the board interior,
    so it runs along the edges (rip: delete its unlocked copper first, on a routed board)"""
    import pcb_maze
    kname = kicad_net_names()
    for net, (x0, y0, x1, y1) in PP.CORRIDORS.items():
        name = kname.get(net, net)
        if rip:
            for t in list(board.GetTracks()):
                if t.GetNetname() == name and not t.IsLocked():
                    board.Delete(t)
        tmp = []
        for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
            z = zone(board, layer, [(x0, y0), (x1, y0), (x1, y1), (x0, y1)], rule_area=True, name="CORRIDOR")
            z.SetDoNotAllowTracks(True); z.SetDoNotAllowVias(True)
            tmp.append(z)
        pcb_maze.route_leftovers(board, only=[name], lock=True, g=0.1, tw=TRACK, clr=CLEAR)
        for z in tmp:
            board.Remove(z)


def do_route(board, passes):
    edge_routes(board)
    audio_ground(board)
    corridor_routes(board)
    pre_route(board)
    stitch_planes(board)
    import pcb_maze                                # plane-net pads outside their plane region: route them first
    pcb_maze.route_leftovers(board, only=[n.split("@")[0] for n in PLANES_IN2], lock=True)
    freeroute(board, passes)                       # full route
    freeroute(board, 20)                           # second run from the result: picks up what is still open
    post_route(board)
    print("routed and saved")
    repair()


def post_route(board):
    board.BuildConnectivity()
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    stitch_grid(board)
    import pcb_gnd
    pcb_gnd.refill(board)
    pcb_gnd.bridge_islands(board)
    import pcb_maze
    pcb_maze.route_leftovers(board, g=0.1, tw=TRACK, clr=CLEAR)
    fill_and_save(board)


def finish():
    """one more incremental Freerouting run on the existing routed board"""
    board = pcbnew.LoadBoard(PCB)
    freeroute(board, 20)
    post_route(board)
    print("finished and saved")


def open_nets(board, skip=("GND",)):
    import pcb_gnd
    out = []
    for name in sorted({p.GetNetname() for p in board.GetPads() if p.GetNetCode() > 0}):
        if name not in skip and len(pcb_gnd.net_components(board, name)) > 1:
            out.append(name)
    return out


def ripup(board, nets, margin=1.2):
    """delete the unlocked signal copper near the straight line of every open connection of `nets`"""
    import pcb_gnd
    corridors = []
    for name in nets:
        comps = pcb_gnd.net_components(board, name)
        src = comps[-1]["items"]
        rest = [it for c in comps[:-1] for it in c["items"]]
        if not src or not rest:
            continue
        a, b = min(((p, q) for p in src for q in rest),
                   key=lambda pq: (pq[0].GetPosition() - pq[1].GetPosition()).EuclideanNorm())
        corridors.append(pcbnew.SHAPE_SEGMENT(a.GetPosition(), b.GetPosition(), MM(2 * margin)))
    gone = 0
    for t in list(board.GetTracks()):
        if t.IsLocked() or t.GetNetname() in PLANE_NETS or t.GetNetname() in nets:
            continue
        L = t.GetLayer() if t.GetClass() != "PCB_VIA" else pcbnew.F_Cu
        sh = t.GetEffectiveShape(L)
        if any(sh.Collide(c, 0) for c in corridors):
            board.Delete(t)
            gone += 1
    print(f"rip-up: {gone} track pieces removed around {len(corridors)} open connections")


def repair(rounds=6):
    import pcb_gnd
    board = pcbnew.LoadBoard(PCB)
    pcb_gnd.refill(board)
    for r in range(rounds):
        nets = open_nets(board)
        print(f"repair round {r}: open nets {nets}")
        if not nets:
            break
        ripup(board, nets, margin=1.2 + 0.8 * r)            # wider corridor each round
        freeroute(board, 30 + 10 * r)
        post_route(board)
        board = pcbnew.LoadBoard(PCB)
    print("repair done, open nets:", open_nets(board))


def redo_art():
    """front silkscreen of the routed board again (title, header pin names, LED names, J1 pin 1, block labels):
    for changes in pcb_art.py without a new placement and route"""
    import pcb_art as A
    board = pcbnew.LoadBoard(PCB)
    for d in list(board.GetDrawings()):
        if d.GetLayer() == pcbnew.F_SilkS and isinstance(d, pcbnew.PCB_TEXT):
            board.Delete(d)
    byref = {f.GetReference(): f for f in board.GetFootprints()}
    fps = {p.ref: (p, byref[p.ref]) for p in D.PARTS}
    A.labels(board, fps)
    A.block_labels(board)
    pcbnew.SaveBoard(PCB, board)
    print("front silkscreen redone")


def polish(rounds=1):
    """re-route the analog nets of pcb_place.POLISH on the routed board: their unlocked copper is deleted and
    Freerouting routes them again around everything else (the repair rounds can leave detours)"""
    kname = kicad_net_names()
    for r in range(rounds):
        board = pcbnew.LoadBoard(PCB)
        names = {kname.get(n, n) for n in PP.POLISH}
        gone = 0
        for t in list(board.GetTracks()):
            if not t.IsLocked() and t.GetNetname() in names:
                board.Delete(t)
                gone += 1
        print(f"polish round {r}: {gone} track pieces of {len(names)} nets removed")
        freeroute(board, 30)
        post_route(board)
    repair(3)


