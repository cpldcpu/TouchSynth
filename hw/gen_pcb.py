FPDIR = S.FPDIR
NS = _uuid.UUID("7a1f3c2e-5b8d-4e6f-9a0b-1c2d3e4f5a6b")
MM = pcbnew.FromMM
W, H = PP.W, PP.H
PLANES_IN2 = PP.PLANES_IN2
