def board_copper(path):
    """track lengths per layer (mm), segment count, via nets of a .kicad_pcb (fields read per block, so locked items
    and any field order are handled)"""
    s = open(path, encoding="utf-8").read()
    length, nseg, vias = {}, 0, []
    for kind, body in re.findall(r"\n\t\((segment|via)\b(.*?)\n\t\)", s, re.S):
        if kind == "segment":
            a = re.search(r"\(start ([\d.\-]+) ([\d.\-]+)\)", body)
            b = re.search(r"\(end ([\d.\-]+) ([\d.\-]+)\)", body)
            layer = re.search(r'\(layer "([^"]+)"\)', body).group(1)
            length[layer] = length.get(layer, 0) + math.hypot(float(b.group(1)) - float(a.group(1)),
                                                              float(b.group(2)) - float(a.group(2)))
            nseg += 1
        else:
            n = re.search(r'\(net "([^"]*)"\)', body)
            vias.append(n.group(1) if n else "")
    nfp = len(re.findall(r"^\t\(footprint ", s, re.M))
    return length, nseg, vias, nfp


