# ----------------------------------------------------------------------------------------------- bus
def cobs_len(n):
    """encoded length of n decoded bytes (no zero runs assumed: worst case) plus the delimiter"""
    return n + 1 + n // 254 + 1


def bus_sizes():
    """decoded sizes from bus.md 4/5: dst type [frame] payload crc"""
    msgs = [("FRAME", False, 2), ("CONFIG", False, 5), ("ASSIGN", False, 1), ("NOTE\\_ON", True, 4),
            ("NOTE\\_OFF", True, 1), ("PITCH", True, 2), ("VOICE\\_STATE", True, 3), ("CTRL", True, 3),
            ("PARAM", True, 3), ("PATCH\\_SELECT", True, 1), ("PATCH\\_DATA (8 values)", False, 3 + 16),
            ("REQUEST", False, 2)]
    lines = [r"\begin{tabular}{@{}l c r r@{}}", r"\toprule", r"Message & Timed & Decoded & On the wire \\",
             r"\midrule"]
    sizes = {}
    for name, timed, pay in msgs:
        dec = 2 + (1 if timed else 0) + pay + 1
        sizes[name] = cobs_len(dec)
        lines.append(f"{name} & {'yes' if timed else ''} & {dec} & {cobs_len(dec)} \\\\")
    chord = sizes["FRAME"] + 8 * sizes["NOTE\\_ON"]
    multi = {"NOTE\\_ON, 8 per-voice records": 2 + 1 + 8 * 4 + 1, "VOICE\\_STATE, 8 per-voice records": 2 + 1 + 8 * 3 + 1}
    lines.append(r"\midrule")
    for name, dec in multi.items():
        lines.append(f"{name} & yes & {dec} & {cobs_len(dec)} \\\\")
    stat("BusMultiChord", cobs_len(multi["NOTE\\_ON, 8 per-voice records"]))
    lines += [r"\midrule", f"FRAME + 8 $\\times$ NOTE\\_ON (8-voice chord) & & & {chord} \\\\",
              r"Budget per frame (1\,Mbaud 8N1) & & & 100 \\", r"\bottomrule", r"\end{tabular}"]
    write("bus_sizes.tex", lines)
    stat("BusChord", chord)


