def floorplan_bp():
    """TikZ floorplan of the backplane from hw/pcb_place_bp.py (KiCad coordinates: y down from the rear edge)."""
    import types
    if "board" not in sys.modules:           # pcb_place_bp needs only board.D; the real hw/board.py pulls in the
        stub = types.ModuleType("board")     # schematic drawing code, which looks for a KiCad installation
        stub.D = BP
        sys.modules["board"] = stub
    import pcb_place_bp as P
    s = 0.125
    L = [r"\begin{tikzpicture}[x=%.3fcm,y=-%.3fcm,font=\scriptsize\sffamily]" % (s, s),
         r"\draw[thick,rounded corners=0.25cm] (0,0) rectangle (%g,%g);" % (P.W, P.H)]
    # card area, guide bands
    x0, y0, x1, y1 = P.RESERVED["slots"]
    L.append(r"\fill[blue!5] (%g,%g) rectangle (%g,%g);" % (x0, 45.0, x1, 95.0))
    for (a, b, c, d) in P.GUIDE_BANDS:
        L.append(r"\fill[pattern=north east lines,pattern color=black!30] (%g,%g) rectangle (%g,%g);" % (a, b, c, d))
    colors = {"leds": "gray!15", "host": "gray!25", "midi": "gray!20", "flash": "violet!12", "nrst": "violet!20",
              "mcu": "blue!18", "adc": "blue!18", "swio": "violet!12", "bus": "cyan!15", "tps": "gray!10",
              "usbc": "orange!20", "power": "red!15", "lineout": "green!25", "mixc": "green!15", "vref": "green!15"}
    labels = {"leds": "LEDs", "host": "USB host", "midi": "MIDI in\\\\(DNP)", "flash": "flash",
              "nrst": "NRST", "mcu": "MCU passives\\\\ADC taps", "swio": "SWIO\\\\pull-ups", "bus": "bus drivers",
              "tps": "test pads", "usbc": "USB-C", "power": "power entry\\\\LDO, soft start",
              "lineout": "line\\\\out", "mixc": "mixer\\\\common\\\\VREF"}
    done = set()
    for k, (a, b, c, d) in P.BLOCKS.items():
        if (a, b, c, d) in done:
            continue
        done.add((a, b, c, d))
        L.append(r"\filldraw[fill=%s,draw=black!40] (%g,%g) rectangle (%g,%g);" % (colors.get(k, "gray!10"),
                                                                                   a, b, c, d))
        if k in labels and k == "usbc":      # the top-left corner of this region is covered by J2 and J1
            L.append(r"\node[align=right,anchor=south east,inner sep=1pt,font=\tiny\sffamily] at (%g,%g) {%s};"
                     % (c - 0.3, d - 0.3, labels[k]))
        elif k in labels:
            L.append(r"\node[align=left,anchor=north west,inner sep=1pt,font=\tiny\sffamily] at (%g,%g) {%s};"
                     % (a + 0.3, b + 0.3, labels[k]))
    # anchors: ICs and connectors as boxes of nominal size (width, height at rotation 0, KiCad orientation)
    size = {"U1": (9, 9, "U1"), "U6": (4, 10, "U6"), "U7": (5.3, 5.3, "U7"), "U8": (4, 5, "U8"),
            "J1": (9, 7.5, "J1"), "J2": (13, 14, "J2"), "J3": (6, 12, "J3"), "J5": (2.5, 10.2, "J5"),
            "J4": (2.5, 5.1, "J4"), "JP1": (2.5, 7.6, "JP1"), "J6": (2.5, 7.6, "J6"), "J7": (2.5, 7.6, "J7"),
            "JP2": (2.5, 7.6, "JP2"), "Y1": (5, 3.2, "Y1"), "U2": (3, 3, "U2"), "SW1": (4, 4, ""),
            "U4": (3, 3, "U4"), "U5": (3, 2, "")}
    A = P.anchors()
    for ref, (w, h, lab) in size.items():
        if ref not in A:
            continue
