def symbol_pins(sch, sym, npins):
    """pin number -> pin name of a library symbol embedded in a KiCad schematic"""
    try:
        s = open(sch, encoding="utf-8").read()
    except OSError:
        print("warning: no", sch, "- port names left empty")
        return {}
    i = s.find(f'(symbol "MCU_WCH_RiscV:{sym}"')
    if i < 0:
        print("warning: symbol", sym, "not in", sch)
        return {}
    out = {}
    for name, number in re.findall(r'\(pin \w+ \w+.*?\(name "([^"]*)".*?\(number "([^"]*)"', s[i:], re.S):
        if number in out or len(out) >= npins:
            break
        out[number] = re.sub(r"~\{(\w+)\}", r"N\1", name)          # ~{RST} (overbar) -> NRST
    return out


