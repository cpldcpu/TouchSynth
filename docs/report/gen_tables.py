# ----------------------------------------------------------------------------------------------- helpers
def tex(s):
    s = str(s)
    rep = [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"), ("$", r"\$"),
           ("µ", r"\textmu{}"), ("Ω", r"$\Omega$"), ("±", r"$\pm$"), ("×", r"$\times$"), ("–", "--"),
           ("≥", r"$\geq$"), ("≤", r"$\leq$"), ("→", r"$\to$"), ("←", r"$\leftarrow$"), ("~", r"\textasciitilde{}"),
           ("^", r"\textasciicircum{}"), ("∥", r"$\parallel$"), ("°", r"\textdegree{}"), (">", r"$>$"),
           ("<", r"$<$")]
    for a, b in rep:
        s = s.replace(a, b)
    return s


def net(n):
    """a net name in typewriter, breakable after underscores"""
    return r"\texttt{" + tex(n).replace(r"\_", r"\_\allowbreak{}") + "}"


def stat(name, value):
    assert re.fullmatch(r"[A-Za-z]+", name), name
    STATS[name] = value


def write(name, lines):
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f:
        f.write("% generated by gen_tables.py -- do not edit\n")
        f.write("\n".join(lines) + "\n")


def num(v, nd=1):
    """number with a real minus sign"""
    s = f"{v:.{nd}f}"
    return s.replace("-", "$-$")


def refs_compact(refs):
    """R1,R2,R3,R5 -> R1--R3, R5"""
    by = {}
    for r in refs:
        m = re.match(r"([A-Z]+)(\d+)$", r)
        by.setdefault(m.group(1), []).append(int(m.group(2)))
    out = []
    for p, ns in sorted(by.items()):
        ns.sort()
        run = [ns[0]]
        for n in ns[1:] + [None]:
            if n is not None and n == run[-1] + 1:
                run.append(n)
                continue
            out.append(f"{p}{run[0]}" if len(run) == 1 else
                       f"{p}{run[0]}, {p}{run[1]}" if len(run) == 2 else f"{p}{run[0]}--{p}{run[-1]}")
            if n is not None:
                run = [n]
    return ", ".join(out)


def package(fp):
    name = fp.split(":")[1]
    for pat, rep in ((r"^[RCL]_(\d{4})_", None), (r"^LED_(\d{4})_", None), (r"^R_Array_Convex_(\w+)", None),
                     (r"^D_(SOD-123|SMA)", None), (r"^(SOT-\d+(-\d)?)", None), (r"^(SOIC-\d+)", None),
                     (r"^(TSSOP-\d+)", None), (r"^(LQFP-\d+)", None), (r"^Crystal_SMD_(\d{4})", None),
                     (r"^SW_Push_1P1T_XKB_(TS-\w+)", None), (r"^(SMDIP-\d)", None), (r"^Fuse_(\d{4})", None)):
        m = re.match(pat, name)
        if m:
            return m.group(1)
    m = re.match(r"Pin(Header|Socket)_(\d)x(\d+)_P2\.54mm_(Horizontal|Vertical)", name)
    if m:
        return f"{m.group(1).lower()} {int(m.group(2))}×{int(m.group(3))}" + (", R/A" if m.group(4) == "Horizontal" else "")
    for key, short in (("USB_C", "USB-C 16P"), ("USB_A", "USB-A"), ("Jack_3.5mm", "3.5 mm jack"),
                       ("TestPoint", "test pad")):
        if name.startswith(key):
            return short
    return name.split("_")[0]


def csv_kv(name, keys=("quantity",), val="value"):
    rows = list(csv.DictReader(open(os.path.join(RES, name), encoding="utf-8")))
    return {tuple(r[k] for k in keys) if len(keys) > 1 else r[keys[0]]: float(r[val]) for r in rows
            if r[val] not in ("", None) and re.fullmatch(r"-?[\d.eE+-]+", r[val])}


# ----------------------------------------------------------------------------------------------- BOM
def assembled(D):
    return [p for p in D.PARTS if p.bom and not p.dnp and p.lcsc]


def bom(D, key, caption, label):
    groups = {}
    for p in assembled(D):
        groups.setdefault((p.value, package(p.fp), p.lcsc), []).append(p.ref)
    rows, total, n = [], 0.0, 0
    for (val, pkg, lcsc), refs in groups.items():
        info = PARTS[lcsc]
        price = float(info["price_usd"])
        total += price * len(refs)
        n += len(refs)
        rows.append((val, len(refs), pkg, lcsc, LIB[info["library"]], price, refs))
    rows.sort(key=lambda x: ({"R": 0, "C": 1}.get(x[6][0][0], 2), x[6][0][0], -x[1], x[0]))
    head = r"\toprule Value & Qty & Package & LCSC & Library & USD/pc & Designators\\ \midrule"
    lines = [r"\begin{longtable}{@{}l r l l l r >{\raggedright\arraybackslash}p{4.1cm}@{}}",
             rf"\caption{{{caption}}}\label{{{label}}}\\",
             head + r"\endfirsthead", head + r"\endhead", r"\bottomrule\endfoot"]
    for val, q, pkg, lcsc, lib, price, refs in rows:
        lines.append(f"{tex(val)} & {q} & {tex(pkg)} & {lcsc} & {lib} & {price:.4f} & "
                     f"{{\\footnotesize {refs_compact(refs)}}}\\\\")
    lines.append(r"\midrule")
    lines.append(f"\\multicolumn{{2}}{{@{{}}l}}{{{n} parts}} & \\multicolumn{{3}}{{l}}{{{len(rows)} BOM lines}} & "
                 f"{total:.2f} & per board (parts only)\\\\")
    lines.append(r"\end{longtable}")
    write(f"bom_{key}.tex", lines)
    basic = sum(1 for x in rows if x[4] == "Basic")
    promo = sorted({(x[3], PARTS[x[3]]["mfr_part"], x[0]) for x in rows if x[4] != "Basic"})
    K = key.capitalize()
    stat(f"{K}Asm", n)
    stat(f"{K}Lines", len(rows))
    stat(f"{K}Basic", basic)
    stat(f"{K}Promo", len(rows) - basic)
    stat(f"{K}Cost", f"{total:.2f}")
    return total, promo


def not_assembled(D, key, caption, label):
    """hand-soldered and not-fitted parts (test points only counted)"""
    lines = [r"\begin{longtable}{@{}l l l l >{\raggedright\arraybackslash}p{6.4cm}@{}}",
             rf"\caption{{{caption}}}\label{{{label}}}\\",
             r"\toprule Ref & Value & Package & Status & Note\\ \midrule\endfirsthead",
             r"\toprule Ref & Value & Package & Status & Note\\ \midrule\endhead",
             r"\bottomrule\endfoot"]
    asm = set(p.ref for p in assembled(D))
    hand = dnp = 0
    sockets = []
    for p in D.PARTS:
        if p.ref in asm or p.ref.startswith("TP"):
            continue
        if p.dnp:
            status, dnp = "not fitted", dnp + 1
        else:
            status, hand = "hand-soldered", hand + 1
        if p.value.startswith("SLOT "):                  # the eight sockets: one line
            sockets.append(p.ref)
            continue
        lines.append(f"{p.ref} & {tex(p.value)} & {tex(package(p.fp))} & {status} & "
                     f"{{\\footnotesize {tex(p.note or '')}}}\\\\")
    if sockets:
        p = [q for q in D.PARTS if q.ref == sockets[0]][0]
        lines.append(f"{refs_compact(sockets)} & SLOT 1--{len(sockets)} & {tex(package(p.fp))} & hand-soldered & "
                     f"{{\\footnotesize {tex(p.note or '')}, 2$\\times$8 female, vertical}}\\\\")
    lines.append(r"\end{longtable}")
    write(f"notasm_{key}.tex", lines)
    K = key.capitalize()
    stat(f"{K}Hand", hand)
    stat(f"{K}Dnp", dnp)
    stat(f"{K}Tp", sum(1 for p in D.PARTS if p.ref.startswith("TP")))


def board_stats(D, key):
    nets = {n for p in D.PARTS for n in p.pins.values() if not n.startswith("NC_")}
    K = key.capitalize()
    stat(f"{K}Parts", len(D.PARTS))
    stat(f"{K}Nets", len(nets))
    stat(f"{K}Sheets", len(D.SHEETS))


