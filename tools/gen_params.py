"""Generate app/js/params.js from docs/params.json, the single parameter table (design report A13).

  python tools/gen_params.py          (run after changing docs/params.json)

Checks the table on the way: unique IDs and keys in 0...63, min <= default <= max, known groups, enum sizes."""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "docs", "params.json")
OUT = os.path.join(ROOT, "app", "js", "params.js")


def check(t):
    groups = {g["key"] for g in t["groups"]}
    ids, keys = set(), set()
    for p in t["params"]:
        assert 0 <= p["id"] <= 63, p
        assert p["id"] not in ids and p["key"] not in keys, p
        ids.add(p["id"]); keys.add(p["key"])
        assert p["group"] in groups, p
        assert p["min"] <= p["default"] <= p["max"], p
        assert -32768 <= p["min"] and p["max"] <= 32767, p
        if "enum" in p:
            assert len(p["enum"]) == p["max"] - p["min"] + 1, p
    return t


def main():
    t = check(json.load(open(SRC, encoding="utf-8")))
    body = json.dumps({"version": t["version"], "groups": t["groups"], "params": t["params"]}, indent=1,
                      ensure_ascii=False)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* generated by tools/gen_params.py from docs/params.json -- do not edit */\n")
        f.write("var TSP = window.TSP = window.TSP || {};\n")
        f.write(f"TSP.PARAMTABLE = {body};\n")
    print(f"{len(t['params'])} parameters, {len(t['groups'])} groups -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
