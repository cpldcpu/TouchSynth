"""Generate tables.h for the TouchSynth firmware from the simulation results (never copy numbers by hand).

  python gen_tables.py

Inputs: docs/results/{s1_cal,s3_cal,s3_cutoff,s4_vca_gain}.csv, sim/lib/voice.py (CV network ratio),
sim/behav/tunes.py (presets and demo tunes).
"""
import csv
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RES = os.path.join(ROOT, "docs", "results")
sys.path.insert(0, os.path.join(ROOT, "sim", "lib"))
sys.path.insert(0, os.path.join(ROOT, "sim", "behav"))
import voice                                            # noqa: E402
import tunes                                            # noqa: E402

F_TIM = 48e6
CODE_FS = 4095                                          # 12-bit CV code = 5 V
V_FS = 5.0
T_RESET = 3e-6
C_INT, RE_DCO, A_TGT = 10e-9, 33e3, 2.0                 # DCO (S1)
CUT_F0 = 16.0                                           # cutoff table origin [Hz], 1/256 octave units above it
N_TIME = 32                                             # envelope / glide time table
T_MIN, T_MAX = 1.0, 4000.0                              # ms


def rows(name):
    with open(os.path.join(RES, name + ".csv"), encoding="utf-8") as fh:
        r = list(csv.reader(fh))
    return r[0], [[float(x) for x in row] for row in r[1:] if row]


def interp(x, xs, ys):
    if x <= xs[0]:
        return ys[0]
    for (x0, y0), (x1, y1) in zip(zip(xs, ys), zip(xs[1:], ys[1:])):
        if x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return ys[-1]


def code(v):
    return max(0, min(CODE_FS, round(v / V_FS * CODE_FS)))


def carray(ctype, name, vals, per_line=12, comment=""):
    body = ",\n    ".join(", ".join(str(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line))
    c = f"  /* {comment} */" if comment else ""
    return f"static const {ctype} {name}[{len(vals)}] = {{{c}\n    {body}\n}};\n"


def main():
    out = ['/* GENERATED by gen_tables.py from the simulation results - do not edit */',
           "#ifndef TABLES_H", "#define TABLES_H", "#include <stdint.h>", ""]

    # ---- DCO: timer counts for the top octave (MIDI 120...132) in 1/16 semitone steps; lower octaves shift left
    counts = [round(F_TIM / (440.0 * 2 ** ((120 + i / 16 - 69) / 12))) for i in range(12 * 16 + 1)]
    out.append(carray("uint16_t", "top_octave_counts", counts, comment="48 MHz timer counts, MIDI 120 + i/16"))
    # CV_AMP code = AMP_K / (counts - RESET_COUNTS): I = A C / (T - t_reset), through the LIN network (S1)
    gain = rows("s1_cal")[1][0][0]
    amp_k = CODE_FS / V_FS * A_TGT * C_INT * RE_DCO / voice.LIN_RATIO / gain * F_TIM
    out.append(f"#define AMP_K {round(amp_k)}UL           /* S1: dco_gain {gain} */")
    out.append(f"#define RESET_COUNTS {round(T_RESET * F_TIM)}  /* 3 us reset pulse */")
    out.append("")

    # ---- cutoff: CV_CUT code vs cutoff in 1/16 octave steps above CUT_F0 (S3 -3 dB table)
    _, cut = rows("s3_cutoff")
    cvs = [r[0] for r in cut]
    lf = [math.log2(r[1]) for r in cut]
    n_oct = math.log2(20000.0 / CUT_F0)
    ctab = [code(interp(math.log2(CUT_F0) + i / 16, lf, cvs)) for i in range(int(n_oct * 16) + 2)]
    out.append(carray("uint16_t", "cut_code", ctab, comment=f"CV_CUT code, cutoff = {CUT_F0:g} Hz * 2^(i/16)"))
    out.append(f"#define CUT_TAB_N {len(ctab)}")
    out.append(f"#define CUT_F0_HZ {CUT_F0:g}")
    out.append("")

    # ---- VCA: CV_VCA code vs linear amplitude 0...64 (inverse S4 law, relative to full gain)
    _, vg = rows("s4_vca_gain")
    vcv = [r[0] for r in vg]
    rel = [10 ** ((r[1] - vg[-1][1]) / 20) for r in vg]
    vtab = [0] + [code(interp(i / 64, rel, vcv)) for i in range(1, 65)]
    out.append(carray("uint16_t", "vca_code", vtab, comment="CV_VCA code for amplitude i/64"))
    out.append("")

    # ---- resonance: threshold of self-oscillation (S3)
    thr = rows("s3_cal")[1][0][0]
    out.append(f"#define RES_THR_CODE {code(thr)}  /* CV_RES {thr} V: self-oscillation threshold (S3) */")
    out.append("")

    # ---- time table for envelopes and glide: 1 ms ... 4 s, log spaced
    tms = [T_MIN * (T_MAX / T_MIN) ** (i / (N_TIME - 1)) for i in range(N_TIME)]
    out.append(carray("uint16_t", "time_ms", [round(t) for t in tms], comment="ms"))
    out.append(carray("uint16_t", "time_coef", [min(65535, round(65536 * math.exp(-1.0 / t))) for t in tms],
                      comment="exp(-1 ms / t) in Q16"))
    out.append(carray("uint16_t", "time_step", [max(1, round(32767 / t)) for t in tms],
                      comment="attack step per ms, Q15 level"))
    out.append(f"#define N_TIME {N_TIME}")
    out.append("")

    def tidx(t_s):
        t = max(T_MIN, min(T_MAX, t_s * 1000))
        return round(math.log(t / T_MIN) / math.log(T_MAX / T_MIN) * (N_TIME - 1))

    def oct256(hz):
        return round(math.log2(hz / CUT_F0) * 256)

    # ---- presets (engine units, see synth.h patch_t)
    def patch(name, p):
        wave = (1 if p.get("saw", 1.0) > 0 else 0) | (2 if p.get("pulse", 0) else 0) | \
               (4 if p.get("sub", 0) else 0) | (8 if p.get("noise", 0) else 0)
        f = p.get("fenv", ("adsr", 0.002, 0.3, 0.0, 0.2))
        a = p.get("aenv", ("adsr", 0.003, 0.3, 1.0, 0.1))
        acc = p.get("accent", {})
        sl = p.get("slide", {})
        fields = [
            f".wave = {wave}", f".pw = {round(p.get('pw', 0.5) * 255)}",
            f".cutoff = {oct256(p.get('cutoff', 8000.0))}", f".res = {round(p.get('res', 0.0) * 200)}",
            f".env_amt = {round(p.get('env_amt', 0.0) * 256)}", f".keytrack = {round(p.get('keytrack', 0.0) * 255)}",
            f".fenv = {{{tidx(f[1])}, {tidx(f[2])}, {round(f[3] * 255)}, {tidx(f[4])}}}",
            f".aenv = {{{tidx(a[1])}, {tidx(a[2])}, {round(a[3] * 255)}, {tidx(a[4])}}}",
            f".glide = {tidx(p['glide']) if p.get('glide', 0) > 0 else 0}",
            f".lfo_rate = {round(p.get('lfo_rate', 5.0) * 100)}", f".lfo_pitch = {round(p.get('lfo_pitch', 0.0))}",
            f".lfo_pw = {round(p.get('lfo_pw', 0.0) * 255)}", f".vol = {round(p.get('vol', 0.9) * 255)}",
            f".acc_env_amt = {round(acc.get('env_amt', p.get('env_amt', 0.0)) * 256)}",
            f".acc_vol = {round(acc.get('vol', p.get('vol', 0.9)) * 255)}",
            f".slide_glide = {tidx(sl.get('glide', 0.06))}",
        ]
        return f"    {{ /* {name} */ " + ", ".join(fields) + " },"

    init = dict(saw=1.0, cutoff=2000.0, env_amt=2.0, res=0.3, keytrack=0.5, vol=0.85,
                fenv=("adsr", 0.002, 0.25, 0.0, 0.2), aenv=("adsr", 0.003, 0.3, 0.8, 0.15))
    names = ["init"] + list(tunes.PRESETS)
    out.append("#define PRESET_TABLE \\")
    out += [patch(n, init if n == "init" else tunes.PRESETS[n]) + " \\" for n in names]
    out.append("")
    out.append("#define PRESET_NAMES " + ", ".join(f'"{n}"' for n in names))
    out.append(f"#define N_PRESETS {len(names)}")
    out.append("")

    # ---- demo tunes: {note, length in 16ths, flags (1 slide, 2 accent)}
    for name, t in tunes.TUNES.items():
        vals = []
        for n, ln, fl in t["steps"]:
            vals.append(f"{{{n}, {ln}, {(1 if 'S' in fl else 0) | (2 if 'A' in fl else 0)}}}")
        body = ",\n    ".join(", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8))
        out.append(f"static const tune_step_t tune_{name}_steps[{len(vals)}] = {{\n    {body}\n}};")
    out.append("#define TUNE_TABLE \\")
    for name, t in tunes.TUNES.items():
        out.append(f"    {{ tune_{name}_steps, {len(t['steps'])}, {t['bpm']}, {names.index(t['preset'])} }}, \\")
    out.append("")
    out.append("#define TUNE_NAMES " + ", ".join(f'"{n}"' for n in tunes.TUNES))
    out.append(f"#define N_TUNES {len(tunes.TUNES)}")
    out.append("")
    out.append("#endif")
    open(os.path.join(HERE, "tables.h"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("tables.h written:", len(counts), "pitch,", len(ctab), "cutoff,", len(vtab), "vca entries;",
          len(names), "presets,", len(tunes.TUNES), "tunes")


if __name__ == "__main__":
    main()
